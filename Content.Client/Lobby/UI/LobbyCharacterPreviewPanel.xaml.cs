    /// <summary>
    /// Sets one dummy per view, in the order South, North, West, East.
    /// Views must not share an entity: displacement map parameters live on a shared shader instance and
    /// are applied when the draw queue is flushed, so views of the same entity would all draw with the
    /// displacement map of the last drawn direction.
    /// </summary>
    public void SetSprites(IReadOnlyList<EntityUid> dummies)
    {
        DeleteDummies();
        _previewDummies.AddRange(dummies);

        ViewBox.DisposeAllChildren();

        var directions = new[] { Direction.South, Direction.North, Direction.West, Direction.East };

        for (var i = 0; i < directions.Length; i++)
        {
            var spriteView = new SpriteView
            {
                OverrideDirection = directions[i],
                Scale = new Vector2(3f, 3f),
                MaxSize = new Vector2(112, 112),
                Stretch = SpriteView.StretchMode.None,
            };
            spriteView.SetEntity(dummies[i]);
            ViewBox.AddChild(spriteView);
        }
    }

    private void DeleteDummies()
    {
        foreach (var dummy in _previewDummies.Distinct())
        {
            if (dummy.IsValid())
                _entManager.DeleteEntity(dummy);
        }

        _previewDummies.Clear();
    }
    // MAID END per direction dummies

    protected override void Dispose(bool disposing)
