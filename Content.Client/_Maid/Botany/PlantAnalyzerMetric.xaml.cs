using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Maid.Botany;

/// <summary>
///     One metric tile of the plant analyzer: title, value, optional target and progress bar.
///     Simplified port of wizden's BotanyMetricControl without its stylesheet.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlantAnalyzerMetric : PanelContainer
{
    private readonly StyleBoxFlat _progressStyle = new();

    public PlantAnalyzerMetric()
    {
        RobustXamlLoader.Load(this);
        Progress.ForegroundStyleBoxOverride = _progressStyle;
        SetAccent(Color.White);
    }

    /// <summary>
    ///     Color of the left border and the progress bar.
    /// </summary>
    public void SetAccent(Color color)
    {
        if (PanelOverride is StyleBoxFlat panel)
            panel.BorderColor = color;

        _progressStyle.BackgroundColor = color;
    }

    public void Update(string title, string value, string? target = null, float? progress = null)
    {
        TitleLabel.Text = title;
        ValueLabel.Text = value;
        TargetLabel.Text = target;
        TargetLabel.Visible = target != null;
        Progress.Visible = progress != null;

        if (progress != null)
            Progress.Value = Math.Clamp(progress.Value, 0f, 1f);
    }
}
