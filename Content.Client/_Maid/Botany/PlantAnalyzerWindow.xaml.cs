/// <summary>
///     Plant analyzer window. Layout and formatting follow wizden's PlantAnalyzerWindow,
///     data comes ready-made from the server in <see cref="PlantAnalyzerState"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PlantAnalyzerWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    private static readonly Color HealthColor = Color.FromHex("#4cbb17");
    private static readonly Color GrowthColor = Color.FromHex("#d1a34a");
    private static readonly Color TemperatureColor = Color.FromHex("#e07a3f");
    private static readonly Color PressureColor = Color.FromHex("#7fb5e0");
    private static readonly Color WaterColor = Color.FromHex("#3a8fd6");
    private static readonly Color NutrientsColor = Color.FromHex("#a76fd6");

    private static readonly Color ColumnColor = Color.FromHex("#1e1e22");
    private static readonly Color SectionColor = Color.FromHex("#25252a");
    private static readonly Color SectionBorderColor = Color.FromHex("#3a3a41");
    private static readonly Color RowColor = Color.FromHex("#2f2f35");

    private static readonly Color BadHealthColor = Color.FromHex("#d9534f");
    private static readonly Color MidHealthColor = Color.FromHex("#e0b13f");

    public PlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ApplyPalette(this);

        Health.SetAccent(HealthColor);
        Growth.SetAccent(GrowthColor);
        Temperature.SetAccent(TemperatureColor);
        Pressure.SetAccent(PressureColor);
        Water.SetAccent(WaterColor);
        Nutrients.SetAccent(NutrientsColor);
    }

    /// <summary>
    ///     Paints the marked panels. Done in code because maid has no stylesheet for this window.
    ///     Headings keep maid's own LabelKeyText style so they match other windows.
    /// </summary>
    private static void ApplyPalette(Control control)
    {
        foreach (var child in control.Children)
        {
            if (child is PanelContainer panel)
            {
                if (panel.HasStyleClass("PlantAnalyzerColumn"))
                {
                    panel.PanelOverride = new StyleBoxFlat { BackgroundColor = ColumnColor };
                }
                else if (panel.HasStyleClass("PlantAnalyzerSection"))
                {
                    panel.PanelOverride = new StyleBoxFlat
                    {
                        BackgroundColor = SectionColor,
                        BorderColor = SectionBorderColor,
                        BorderThickness = new Thickness(1),
                    };
                }
            }
            ApplyPalette(child);
        }
    }

    public void Update(PlantAnalyzerState state)
    {
        if (_entityManager.TryGetEntity(state.Target, out var target))
            PlantSprite.SetEntity(target.Value);

        PlantName.Text = state.Name;
        UpdateTextList(Warnings, state.Warnings, "botany-ui-warnings-none", markup: true);

        // An empty tray has nothing but its warnings to show.
        TraitsSection.Visible = state.HasSeed;
        Details.Visible = state.HasSeed;
        if (!state.HasSeed || state.Traits is not { } traits)
            return;

        UpdateTraits(state, traits);
        UpdateStatus(state, traits);
        UpdateConditions(state);
        UpdateGases(Consumed, state.ConsumedGases);
        UpdateGases(Exuded, state.ExudedGases);
        UpdateChemicals(state.Chemicals);
        UpdateTextList(Mutations, state.Mutations, "botany-ui-mutations-none");

        MutationLevels.Visible = state.Holder != null;
        if (state.Holder is { } holder)
        {
            MutationLevel.Text = $"{holder.MutationLevel:0.#}";
            MutationMod.Text = $"{holder.MutationMod:0.#}";
        }
    }

    private void UpdateTraits(PlantAnalyzerState state, PlantAnalyzerTraits traits)
    {
        Age.Text = state.Holder is { } holder ? $"{holder.Age}" : "-";
        GrowthStage.Text = state.Holder is { } h ? $"{h.GrowthStage} / {traits.GrowthStages}" : $"- / {traits.GrowthStages}";
        HarvestType.Text = Loc.GetString("botany-ui-harvest-type-value", ("type", state.HarvestType));

        Endurance.Text = $"{traits.Endurance:0.#}";
        Yield.Text = $"{traits.Yield}";
        Lifespan.Text = $"{traits.Lifespan:0.#}";
        Maturation.Text = $"{traits.Maturation:0.#}";
        Production.Text = $"{traits.Production:0.#}";
        Potency.Text = $"{traits.Potency:0.#}";

        var proto = state.PrototypeTraits;
        UpdateDelta(EnduranceDelta, traits.Endurance, proto?.Endurance);
        UpdateDelta(YieldDelta, traits.Yield, proto?.Yield);
        UpdateDelta(LifespanDelta, traits.Lifespan, proto?.Lifespan);
        // Lower maturation and production times are better.
        UpdateDelta(MaturationDelta, traits.Maturation, proto?.Maturation, invert: true);
        UpdateDelta(ProductionDelta, traits.Production, proto?.Production, invert: true);
        UpdateDelta(PotencyDelta, traits.Potency, proto?.Potency);
    }

    private static void UpdateDelta(Label label, float value, float? prototypeValue, bool invert = false)
    {
        if (prototypeValue is not { } original)
        {
            label.Text = string.Empty;
            return;
        }

        var delta = value - original;
        label.Text = $"({delta:+#.#;-#.#;0})";
        label.FontColorOverride = delta switch
        {
            > 0f => invert ? Color.Crimson : Color.LimeGreen,
            < 0f => invert ? Color.LimeGreen : Color.Crimson,
            _ => Color.DimGray,
        };
    }

    private void UpdateStatus(PlantAnalyzerState state, PlantAnalyzerTraits traits)
    {
        StatusSection.Visible = state.Holder != null;
        if (state.Holder is not { } holder)
            return;

        if (holder.Dead)
        {
            Health.SetAccent(BadHealthColor);
            Health.Update(Loc.GetString("botany-ui-health"), Loc.GetString("plant-analyzer-dead"), progress: 0f);
            Growth.Update(Loc.GetString("botany-ui-growth"), "-");
            return;
        }

        var healthFraction = traits.Endurance > 0f ? Math.Clamp(holder.Health / traits.Endurance, 0f, 1f) : 1f;
        Health.SetAccent(GetHealthColor(healthFraction));
        Health.Update(Loc.GetString("botany-ui-health"),
            $"{holder.Health:0.#} / {traits.Endurance:0.#}",
            progress: healthFraction);

        if (holder.ReadyForHarvest)
        {
            Growth.Update(Loc.GetString("botany-ui-growth"), Loc.GetString("botany-ui-harvest-ready"), progress: 1f);
            return;
        }

        var maturation = Math.Max(traits.Maturation, 1f);
        Growth.Update(Loc.GetString("botany-ui-growth"),
            $"{holder.Age} / {maturation:0.#} {Loc.GetString("botany-ui-unit-cycles")}",
            progress: holder.Age / maturation);
    }

    /// <summary>
    ///     Red at zero health, yellow at half, green at full.
    /// </summary>
    private static Color GetHealthColor(float fraction)
    {
        return fraction < 0.5f
            ? Color.InterpolateBetween(BadHealthColor, MidHealthColor, fraction * 2f)
            : Color.InterpolateBetween(MidHealthColor, HealthColor, (fraction - 0.5f) * 2f);
    }

    private void UpdateConditions(PlantAnalyzerState state)
    {
        UpdateRange(Temperature,
            "botany-ui-temperature",
            state.IdealHeat - state.HeatTolerance,
            state.IdealHeat + state.HeatTolerance,
            "units-kelvin");
        UpdateRange(Pressure,
            "botany-ui-pressure",
            state.LowPressureTolerance,
            state.HighPressureTolerance,
            "units-k-pascal");

        UpdateResource(Water, "botany-ui-water", state.Holder?.WaterLevel, state.WaterConsumption);
        UpdateResource(Nutrients, "botany-ui-nutrients", state.Holder?.NutritionLevel, state.NutrientConsumption);
    }

    private static void UpdateRange(PlantAnalyzerMetric metric, string name, float minimum, float maximum, string unit)
    {
        var value = Loc.GetString("botany-ui-condition-range",
            ("minimum", $"{minimum:0.#}"),
            ("maximum", $"{maximum:0.#}"),
            ("unit", Loc.GetString(unit)));

        metric.Update(Loc.GetString(name), value);
    }

    /// <summary>
    ///     Tray level (if a tray is scanned) plus how much the plant uses per cycle.
    /// </summary>
    private static void UpdateResource(PlantAnalyzerMetric metric, string name, float? level, float consumption)
    {
        var usage = Loc.GetString("plant-analyzer-consumption", ("amount", $"{consumption:0.##}"));

        if (level is { } current)
            metric.Update(Loc.GetString(name), $"{current:0} / 100", usage, current / 100f);
        else
            metric.Update(Loc.GetString(name), usage);
    }

    private void UpdateGases(BoxContainer container, Dictionary<Gas, float> gases)
    {
        var atmos = _entityManager.System<SharedAtmosphereSystem>();
        var unit = Loc.GetString("plant-analyzer-unit-mol");
        var rows = gases
            .Where(g => g.Value > 0f)
            .Select(g =>
            {
                var gas = atmos.GetGas(g.Key);
                var color = Color.TryFromHex("#" + gas.Color) ?? Color.White;
                return (Loc.GetString(gas.Name), $"{g.Value:0.##} {unit}", color);
            });

        UpdateRows(container, rows, "botany-ui-gases-none");
    }

    private void UpdateChemicals(Dictionary<string, float> chemicals)
    {
        var unit = Loc.GetString("plant-analyzer-unit-u");
        var rows = chemicals.Select(c =>
        {
            if (_prototype.TryIndex<ReagentPrototype>(c.Key, out var reagent))
                return (reagent.LocalizedName, $"{c.Value:0.##} {unit}", reagent.SubstanceColor);

            return (c.Key, $"{c.Value:0.##} {unit}", Color.White);
        });

        UpdateRows(Chemicals, rows, "botany-ui-chemicals-none");
    }

    /// <summary>
    ///     Name / amount rows with a color strip on the right, like wizden's gas and reagent displays.
    /// </summary>
    private static void UpdateRows(Control container, IEnumerable<(string Name, string Amount, Color Color)> rows, string emptyLoc)
    {
        container.RemoveAllChildren();
        var any = false;
        foreach (var (name, amount, color) in rows)
        {
            any = true;

            var row = new PanelContainer
            {
                Margin = new Thickness(0, 1),
                PanelOverride = new StyleBoxFlat { BackgroundColor = RowColor },
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(6, 2, 0, 2),
            };
            content.AddChild(new Label { Text = name, HorizontalExpand = true, ClipText = true });
            content.AddChild(new Label { Text = amount, StyleClasses = { "LabelSubText" }, Margin = new Thickness(8, 0) });
            content.AddChild(new PanelContainer
            {
                SetWidth = 4,
                VerticalExpand = true,
                PanelOverride = new StyleBoxFlat { BackgroundColor = color },
            });

            row.AddChild(content);
            container.AddChild(row);
        }

        if (!any)
            container.AddChild(new Label { Text = Loc.GetString(emptyLoc), StyleClasses = { "LabelSubText" } });
    }

    private static void UpdateTextList(Control container, IEnumerable<string> lines, string emptyLoc, bool markup = false)
    {
        container.RemoveAllChildren();
        var any = false;
        foreach (var line in lines.Where(l => !string.IsNullOrEmpty(l)))
        {
            any = true;
            var label = new RichTextLabel { Margin = new Thickness(4, 1) };
            var text = markup ? line : FormattedMessage.EscapeText(line);
            label.SetMessage(FormattedMessage.FromMarkupPermissive($"[bullet/][font size=11]{text}[/font]"));
            container.AddChild(label);
        }

        if (!any)
            container.AddChild(new Label { Text = Loc.GetString(emptyLoc), StyleClasses = { "LabelSubText" } });
    }
}
