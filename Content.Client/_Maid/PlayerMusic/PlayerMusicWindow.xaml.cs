using System.IO;
using Content.Shared._Maid.PlayerMusic;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Maid.PlayerMusic;

[GenerateTypedNameReferences]
public sealed partial class PlayerMusicWindow : FancyWindow
{
    [Dependency] private readonly IFileDialogManager _dialog = default!;
    [Dependency] private readonly IConfigurationManager _cfg = default!;

    public event Action<int>? OnPlayTrack;
    public event Action? OnStop;
    public event Action<bool>? OnRepeat;
    public event Action<string, byte[]>? OnUpload;

    private byte[]? _pending;
    private bool _dialogOpen;
    private bool _canRecord;

    public PlayerMusicWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StopButton.OnPressed += _ => OnStop?.Invoke();
        RepeatBox.OnToggled += args => OnRepeat?.Invoke(args.Pressed);
        ChooseButton.OnPressed += _ => ChooseFile();
        UploadButton.OnPressed += _ => Upload();
        NameField.OnTextChanged += _ => UpdateUploadButton();

        UpdateUploadButton();
    }

    public void Update(PlayerMusicBoomboxComponent comp)
    {
        if (!comp.HasCassette)
        {
            CassetteLabel.Text = Loc.GetString("maid-music-ui-no-cassette");
        }
        else
        {
            CassetteLabel.Text = Loc.GetString("maid-music-ui-cassette-slots",
                ("used", comp.CassetteTracks.Count),
                ("max", comp.CassetteMaxTracks));
        }

        NowPlayingLabel.Text = comp.StartedAt != null
            ? Loc.GetString("maid-music-ui-now-playing", ("name", comp.SongName ?? "?"))
            : Loc.GetString("maid-music-ui-stopped");

        TrackList.RemoveAllChildren();
        for (var i = 0; i < comp.CassetteTracks.Count; i++)
        {
            var index = i;
            var track = comp.CassetteTracks[i];
            var playing = comp.StartedAt != null && comp.SongId == track.Id;

            var button = new Button
            {
                Text = Loc.GetString(playing ? "maid-music-ui-track-playing" : "maid-music-ui-track",
                    ("num", i + 1),
                    ("name", track.Name)),
                HorizontalExpand = true,
            };
            button.OnPressed += _ => OnPlayTrack?.Invoke(index);
            TrackList.AddChild(button);
        }

        StopButton.Disabled = comp.StartedAt == null;
        RepeatBox.Pressed = comp.Repeat;

        _canRecord = comp.HasCassette && comp.CassetteTracks.Count < comp.CassetteMaxTracks;
        ChooseButton.Disabled = !_canRecord;
        UpdateUploadButton();
    }

    private async void ChooseFile()
    {
        if (_dialogOpen)
            return;

        _dialogOpen = true;
        var filters = new FileDialogFilters(new FileDialogFilters.Group("ogg"));
        await using var file = await _dialog.OpenFile(filters);
        _dialogOpen = false;

        if (Disposed || file == null)
            return;

        var max = _cfg.GetCVar(PlayerMusicCVars.MaxSongBytes);

        using var memory = new MemoryStream();
        await file.CopyToAsync(memory);

        if (Disposed)
            return;

        if (memory.Length > max)
        {
            _pending = null;
            FileLabel.Text = string.Empty;
            StatusLabel.Text = Loc.GetString("maid-music-ui-too-big", ("max", FormatMb((int) max)));
            UpdateUploadButton();
            return;
        }

        var bytes = memory.ToArray();

        // Same checks as on the server, so a bad file is not even sent
        if (!PlayerMusicOgg.TryAnalyze(bytes, out var info))
        {
            RejectFile("maid-music-ui-bad-file");
            return;
        }

        var maxSeconds = _cfg.GetCVar(PlayerMusicCVars.MaxSongSeconds);
        if (info.Seconds > maxSeconds)
        {
            RejectFile("maid-music-ui-too-long", ("max", maxSeconds));
            return;
        }

        if (info.DecodedBytes > _cfg.GetCVar(PlayerMusicCVars.MaxDecodedBytes))
        {
            RejectFile("maid-music-ui-too-heavy");
            return;
        }

        _pending = bytes;
        FileLabel.Text = Loc.GetString("maid-music-ui-file-ready", ("size", FormatMb(_pending.Length)));
        StatusLabel.Text = string.Empty;
        UpdateUploadButton();
    }

    private void RejectFile(string locKey, params (string, object)[] args)
    {
        _pending = null;
        FileLabel.Text = string.Empty;
        StatusLabel.Text = Loc.GetString(locKey, args);
        UpdateUploadButton();
    }

    private void Upload()
    {
        if (_pending == null || NameField.Text.Trim().Length == 0)
            return;

        OnUpload?.Invoke(NameField.Text, _pending);

        _pending = null;
        NameField.Clear();
        FileLabel.Text = string.Empty;
        StatusLabel.Text = Loc.GetString("maid-music-ui-sent");
        UpdateUploadButton();
    }

    private void UpdateUploadButton()
    {
        UploadButton.Disabled = !_canRecord || _pending == null || NameField.Text.Trim().Length == 0;
    }

    private static string FormatMb(int bytes)
    {
        return (bytes / 1_000_000f).ToString("0.##");
    }
}
