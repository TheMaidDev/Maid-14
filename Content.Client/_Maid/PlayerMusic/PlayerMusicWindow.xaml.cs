using System.IO;
using System.Text;
using Content.Shared._Maid.PlayerMusic;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Log;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Maid.PlayerMusic;

[GenerateTypedNameReferences]
public sealed partial class PlayerMusicWindow : FancyWindow
{
    [Dependency] private readonly IFileDialogManager _dialog = default!;
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    public event Action<int, string, float>? OnPlayTrack;
    public event Action? OnStop;
    public event Action<bool>? OnRepeat;
    public event Action<float>? OnSeek;
    public event Action<float>? OnSetVolume;
    public event Action<int, string>? OnDeleteTrack;
    public event Action<string, byte[]>? OnUpload;

    private byte[]? _pending;
    private bool _dialogOpen;
    private bool _canRecord;
    private int _maxSongBytes = PlayerMusicLimits.HardMaxSongBytes;
    private int _maxSongSeconds = PlayerMusicLimits.HardMaxSongSeconds;
    private List<PlayerMusicTrack> _tracks = new();
    private TimeSpan? _startedAt;
    private double _duration;
    private bool _repeat;
    private string? _currentSongId;
    private TimeSpan? _lastVolumeSent;
    private int _seekSecond = -1;
    private string _trackSignature = string.Empty;

    private static readonly TimeSpan VolumeSendCooldown = TimeSpan.FromMilliseconds(100);

    public PlayerMusicWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StopButton.OnPressed += _ => OnStop?.Invoke();
        StartButton.OnPressed += _ => Start();
        RepeatButton.OnToggled += args => OnRepeat?.Invoke(args.Pressed);
        ChooseButton.OnPressed += _ => ChooseFile();
        UploadButton.OnPressed += _ => Upload();
        NameField.OnTextChanged += _ => UpdateUploadButton();
        VolumeSlider.OnValueChanged += _ =>
        {
            UpdateVolumeLabel();
            SendVolume(false);
        };
        VolumeSlider.OnReleased += _ => SendVolume(true);
        SeekSlider.OnValueChanged += _ => UpdateSeekLabel();
        SeekSlider.OnReleased += _ =>
        {
            _seekSecond = -1;
            OnSeek?.Invoke(SeekSlider.Value);
        };

        UpdateUploadButton();
    }

    public void Update(PlayerMusicBoomboxComponent comp)
    {
        var previousStart = _startedAt;
        var previousDuration = _duration;
        var previousRepeat = _repeat;

        _tracks = comp.CassetteTracks;
        _startedAt = comp.StartedAt;
        _duration = comp.HasCassette ? comp.SongDuration.TotalSeconds : 0;
        _repeat = comp.Repeat;
        _currentSongId = comp.SongId;
        _canRecord = comp.HasCassette &&
                     (comp.CassetteMaxTracks <= 0 || comp.CassetteTracks.Count < comp.CassetteMaxTracks);
        _maxSongBytes = Math.Min(comp.CassetteMaxSongBytes, PlayerMusicLimits.HardMaxSongBytes);
        _maxSongSeconds = Math.Min(comp.CassetteMaxSongSeconds, PlayerMusicLimits.HardMaxSongSeconds);

        var hasSong = _duration > 0;

        if (!VolumeSlider.Grabbed)
            VolumeSlider.SetValueWithoutEvent(comp.VolumeScale * 100f);
        UpdateVolumeLabel();

        if (!SeekSlider.Grabbed)
        {
            SeekSlider.MaxValue = hasSong ? (float) _duration : 0f;
            UpdateSeekLabel();
            _seekSecond = (int) SeekSlider.Value;
        }

        // A song that ended by itself must not leave the start point at its very end
        if (!hasSong)
        {
            SeekSlider.MaxValue = 0f;
            ResetSeek();
        }
        else if (previousStart is { } started && comp.StartedAt == null && previousDuration > 0)
        {
            var elapsed = (_timing.CurTime - started).TotalSeconds;
            if (previousRepeat)
                elapsed %= previousDuration;

            if (elapsed >= previousDuration - 0.5)
                ResetSeek();
        }

        var signature = GetTrackSignature(comp);
        if (signature != _trackSignature)
        {
            _trackSignature = signature;
            RebuildTrackList(comp);
        }

        StopButton.Disabled = comp.StartedAt == null;
        StartButton.Disabled = !comp.HasCassette || _tracks.Count == 0;
        RepeatButton.Pressed = comp.Repeat;

        ChooseButton.Disabled = !_canRecord;
        UpdateUploadButton();
    }

    private void RebuildTrackList(PlayerMusicBoomboxComponent comp)
    {
        TrackList.RemoveAllChildren();
        for (var i = 0; i < comp.CassetteTracks.Count; i++)
        {
            var index = i;
            var track = comp.CassetteTracks[i];
            var playing = comp.StartedAt != null && comp.SongId == track.Id;

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            var button = new Button
            {
                Text = Loc.GetString(playing ? "maid-music-ui-track-playing" : "maid-music-ui-track",
                    ("num", i + 1),
                    ("name", track.Name)),
                HorizontalExpand = true,
            };
            button.OnPressed += _ => OnPlayTrack?.Invoke(index, track.Id, 0f);
            row.AddChild(button);

            if (comp.CassetteAllowsTrackRemoval)
            {
                var delete = new Button
                {
                    Text = Loc.GetString("maid-music-ui-delete"),
                };
                delete.OnPressed += _ => OnDeleteTrack?.Invoke(index, track.Id);
                row.AddChild(delete);
            }

            TrackList.AddChild(row);
        }
    }

    private static string GetTrackSignature(PlayerMusicBoomboxComponent comp)
    {
        var builder = new StringBuilder();
        builder.Append(comp.HasCassette).Append('\u001f');
        builder.Append(comp.CassetteAllowsTrackRemoval).Append('\u001f');
        builder.Append(comp.StartedAt != null).Append('\u001f');
        builder.Append(comp.SongId).Append('\u001f');

        foreach (var track in comp.CassetteTracks)
            builder.Append(track.Id).Append('\u001e').Append(track.Name).Append('\u001f');

        return builder.ToString();
    }

    private void ResetSeek()
    {
        SeekSlider.SetValueWithoutEvent(0f);
        _seekSecond = 0;
        UpdateSeekLabel();
    }

    public void SetStatus(string locKey, string text, float number)
    {
        StatusLabel.Text = locKey switch
        {
            "maid-music-cooldown" => Loc.GetString(locKey, ("seconds", (int) MathF.Ceiling(number))),
            "maid-music-too-big" => Loc.GetString(locKey, ("max", number)),
            "maid-music-ui-too-long" => Loc.GetString(locKey, ("max", (int) number)),
            "maid-music-recorded" => Loc.GetString(locKey, ("name", text)),
            _ => Loc.GetString(locKey),
        };
    }

    public void SetUploadProgress(int percent)
    {
        StatusLabel.Text = Loc.GetString("maid-music-ui-recording-progress", ("percent", percent));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (SeekSlider.Grabbed || _startedAt is not { } started || _duration <= 0)
            return;

        var elapsed = (_timing.CurTime - started).TotalSeconds;
        if (_repeat)
            elapsed %= _duration;

        elapsed = Math.Clamp(elapsed, 0, _duration);
        SeekSlider.SetValueWithoutEvent((float) elapsed);

        var second = (int) elapsed;
        if (second == _seekSecond)
            return;

        _seekSecond = second;
        UpdateSeekLabel();
    }

    private void Start()
    {
        if (_tracks.Count == 0)
            return;

        var index = 0;
        if (_currentSongId != null)
        {
            var found = _tracks.FindIndex(track => track.Id == _currentSongId);
            if (found >= 0)
                index = found;
        }

        OnPlayTrack?.Invoke(index, _tracks[index].Id, SeekSlider.Value);
    }

    private void UpdateVolumeLabel()
    {
        VolumeLabel.Text = Loc.GetString("maid-music-ui-volume-label",
            ("value", MathF.Round(VolumeSlider.Value)));
    }

    private void SendVolume(bool force)
    {
        var now = _timing.CurTime;
        if (!force && _lastVolumeSent is { } last && now - last < VolumeSendCooldown)
            return;

        _lastVolumeSent = now;
        OnSetVolume?.Invoke(VolumeSlider.Value / 100f);
    }

    private void UpdateSeekLabel()
    {
        SeekLabel.Text = Loc.GetString("maid-music-ui-time-label",
            ("position", FormatTime(SeekSlider.Value)),
            ("duration", FormatTime(SeekSlider.MaxValue)));
    }

    private static string FormatTime(float seconds)
    {
        return TimeSpan.FromSeconds(Math.Max(seconds, 0f)).ToString(@"mm\:ss");
    }

    private async void ChooseFile()
    {
        if (_dialogOpen)
            return;

        _dialogOpen = true;
        UpdateUploadButton();
        try
        {
            var filters = new FileDialogFilters(new FileDialogFilters.Group("ogg"));
            await using var file = await _dialog.OpenFile(filters);

            if (Disposed || file == null)
                return;

            // The same ceilings as on the server: a song above the client hard limit
            // would be stored and then silently ignored on download
            var max = _maxSongBytes;

            // Reject oversized files before reading them into memory
            if (file.CanSeek && file.Length > max)
            {
                RejectFile("maid-music-too-big", ("max", FormatMb(max)));
                return;
            }

            byte[] bytes;
            if (file.CanSeek)
            {
                bytes = new byte[(int) file.Length];
                await file.ReadExactlyAsync(bytes);
            }
            else
            {
                using var memory = new MemoryStream();
                await file.CopyToAsync(memory);

                if (Disposed)
                    return;

                if (memory.Length > max)
                {
                    RejectFile("maid-music-too-big", ("max", FormatMb(max)));
                    return;
                }

                bytes = memory.ToArray();
            }

            if (Disposed)
                return;

            // Same checks as on the server, so a bad file is not even sent
            if (!PlayerMusicOgg.TryAnalyze(bytes, out var info))
            {
                RejectFile("maid-music-ui-bad-file");
                return;
            }

            if (info.Channels != 1)
            {
                RejectFile("maid-music-stereo");
                return;
            }

            var maxSeconds = _maxSongSeconds;
            if (info.Seconds > maxSeconds)
            {
                RejectFile("maid-music-ui-too-long", ("max", maxSeconds));
                return;
            }

            var maxDecoded = Math.Min((long) _cfg.GetCVar(PlayerMusicCVars.MaxDecodedBytes),
                PlayerMusicLimits.HardMaxDecodedBytes);
            if (info.DecodedBytes > maxDecoded)
            {
                RejectFile("maid-music-ui-too-heavy");
                return;
            }

            _pending = bytes;
            FileLabel.Text = Loc.GetString("maid-music-ui-file-ready", ("size", FormatMb(_pending.Length)));
            StatusLabel.Text = string.Empty;
            UpdateUploadButton();
        }
        catch (Exception e)
        {
            // An exception in an async void handler would crash the client
            Logger.GetSawmill("playermusic").Error($"PlayerMusic: file dialog failed: {e}");

            if (!Disposed)
                RejectFile("maid-music-ui-error");
        }
        finally
        {
            _dialogOpen = false;
            UpdateUploadButton();
        }
    }

    private void RejectFile(string locKey, params (string, object)[] args)
    {
        _pending = null;
        FileLabel.Text = string.Empty;
        StatusLabel.Text = Loc.GetString(locKey, args);
        UpdateUploadButton();
    }

    private void Upload()
    {
        // The dialog open guard keeps the previous selection from being sent
        // while a replacement file is still being read
        if (_dialogOpen || _pending == null || NameField.Text.Trim().Length == 0)
            return;

        OnUpload?.Invoke(NameField.Text, _pending);

        _pending = null;
        NameField.Clear();
        FileLabel.Text = string.Empty;
        StatusLabel.Text = Loc.GetString("maid-music-ui-sent");
        UpdateUploadButton();
    }

    private void UpdateUploadButton()
    {
        UploadButton.Disabled = !_canRecord || _dialogOpen || _pending == null || NameField.Text.Trim().Length == 0;
    }

    private static string FormatMb(int bytes)
    {
        return (bytes / 1_000_000f).ToString("0.##");
    }
}
