using System.Linq;
using System.Numerics;
using Content.Shared._Maid.DocumentPrinter;
using Content.Shared.Cargo;
using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Player;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Maid.DocumentPrinter;

[GenerateTypedNameReferences]
public sealed partial class DocumentPrinterWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IPlayerManager _player = default!;

    private readonly SpriteSystem _sprite;

    private DocumentPrinterBuiState? _state;

    public event Action<EntProtoId>? OnPrint;
    public event Action<string, string, string, int>? OnOrder;

    public DocumentPrinterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entMan.System<SpriteSystem>();

        // The state is shared by everyone looking at the printer, so the requester comes from the local player.
        if (_player.LocalEntity is { } local)
        {
            var name = Identity.Name(local, _entMan);
            Requester.Text = name.Length <= SharedCargoSystem.MaxOrderRequesterLength
                ? name
                : name[..SharedCargoSystem.MaxOrderRequesterLength];
        }

        Tabs.SetTabTitle(0, Loc.GetString("doc-printer-tab-documents"));
        Tabs.SetTabTitle(1, Loc.GetString("doc-printer-tab-cargo"));

        Amount.SetButtons(new List<int> {-4, -2, -1}, new List<int> {1, 2, 4});
        Amount.IsValid = n => n > 0;
        Requester.IsValid = text => text.Length <= SharedCargoSystem.MaxOrderRequesterLength;
        Reason.IsValid = text => text.Length <= SharedCargoSystem.MaxOrderReasonLength;

        DocumentSearch.OnTextChanged += _ => PopulateDocuments();
        ProductSearch.OnTextChanged += _ => PopulateProducts();
    }

    public void UpdateState(DocumentPrinterBuiState state)
    {
        _state = state;
        PopulateDocuments();
        PopulateProducts();
    }

    private void PopulateDocuments()
    {
        Documents.RemoveAllChildren();
        if (_state == null)
            return;

        var search = DocumentSearch.Text.Trim();
        foreach (var section in _state.Sections)
        {
            var buttons = new List<Button>();
            foreach (var document in section.Documents)
            {
                if (!_proto.TryIndex(document, out var proto))
                    continue;

                if (search.Length != 0 && !proto.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase))
                    continue;

                var button = new Button { Text = proto.Name, HorizontalExpand = true, ClipText = true };
                var id = document;
                button.OnPressed += _ => OnPrint?.Invoke(id);
                buttons.Add(button);
            }

            if (buttons.Count == 0)
                continue;

            Documents.AddChild(new Label
            {
                Text = Loc.GetString(section.Name),
                Margin = new Thickness(0, 6, 0, 2),
                StyleClasses = { "LabelHeading" },
            });

            foreach (var button in buttons)
            {
                Documents.AddChild(button);
            }
        }
    }

    private void PopulateProducts()
    {
        Products.RemoveAllChildren();
        if (_state == null)
            return;

        // If we have 0 products (i. e. cargo component not provided) then hide
        Tabs.SetTabVisible(1, _state.Products.Count > 0);

        var products = _state.Products
            .Select(id => _proto.Index(id))
            .OrderBy(p => p.Name, StringComparer.CurrentCultureIgnoreCase);

        var search = ProductSearch.Text.Trim();
        foreach (var product in products)
        {
            if (search.Length != 0 &&
                !product.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase) &&
                !product.Description.Contains(search, StringComparison.CurrentCultureIgnoreCase))
            {
                continue;
            }

            var button = new ContainerButton();

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(new TextureRect
            {
                Texture = _sprite.Frame0(product.Icon),
                TextureScale = new Vector2(1, 1),
                MinSize = new Vector2(32, 32),
            });
            row.AddChild(new Label
            {
                Text = product.Name,
                HorizontalExpand = true,
                ClipText = true,
                ToolTip = product.Description,
            });
            row.AddChild(new Label
            {
                Text = Loc.GetString("cargo-console-menu-points-amount", ("amount", product.Cost.ToString())),
                Margin = new Thickness(6, 0),
            });

            button.OnPressed += _ => OnOrder?.Invoke(Requester.Text, Reason.Text, product.ID, Amount.Value);

            button.AddChild(row);
            Products.AddChild(button);
        }
    }
}
