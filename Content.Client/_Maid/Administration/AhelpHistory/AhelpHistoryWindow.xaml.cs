using System.Globalization;
using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Maid.Administration.AhelpHistory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Timing;

namespace Content.Client._Maid.Administration.AhelpHistory;

[GenerateTypedNameReferences]
public sealed partial class AhelpHistoryWindow : FancyWindow
{
    public event Action? FiltersApplied;
    public event Action? PageBackRequested;
    public event Action? PageNextRequested;
    public event Action<int>? PageSizeChanged;
    public event Action<AhelpHistoryEntry>? MoveToRequested;

    private enum PendingScrollSpot
    {
        None,
        Top,
        Bottom,
    }

    private PendingScrollSpot _pendingScrollSpot = PendingScrollSpot.None;

    private const int DefaultPageSize = 200;
    private readonly int[] _pageSizeOptions = { 100, 200, 300, 500 };

    public int PageSize { get; private set; } = DefaultPageSize;

    public void RequestScrollBottom()
    {
        _pendingScrollSpot = PendingScrollSpot.Bottom;
    }

    public void RequestScrollTop()
    {
        _pendingScrollSpot = PendingScrollSpot.Top;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_pendingScrollSpot == PendingScrollSpot.None)
            return;

        if (!HistoryContainer.Children.Any(c => c.DesiredSize.Y > 0f))
            return;

        switch (_pendingScrollSpot)
        {
            case PendingScrollSpot.Top:
                LogScroll.VScrollTarget = 0f;
                break;
            case PendingScrollSpot.Bottom:
                LogScroll.VScrollTarget = float.MaxValue;
                break;
            default:
                _pendingScrollSpot = PendingScrollSpot.None;
                return;
        }

        if (MathHelper.CloseToPercent(LogScroll.VScroll, LogScroll.VScrollTarget))
            _pendingScrollSpot = PendingScrollSpot.None;
    }

    public AhelpHistoryWindow()
    {
        RobustXamlLoader.Load(this);

        SearchButton.OnPressed += _ => FiltersApplied?.Invoke();

        foreach (var edit in new[] { FilterText, FilterRound, FilterFrom, FilterTo })
        {
            edit.OnTextEntered += _ => FiltersApplied?.Invoke();
        }

        PrevPageButton.OnPressed += _ => PageBackRequested?.Invoke();
        NextPageButton.OnPressed += _ => PageNextRequested?.Invoke();

        foreach (var size in _pageSizeOptions)
        {
            PageSizeOption.AddItem(size.ToString(), id: size);
        }

        PageSizeOption.SelectId(DefaultPageSize);
        PageSizeOption.OnItemSelected += args =>
        {
            PageSizeOption.SelectId(args.Id);
            if (args.Id == PageSize)
                return;
            PageSize = args.Id;
            PageSizeChanged?.Invoke(args.Id);
        };
    }

    public void ClearFilters()
    {
        foreach (var edit in new[] { FilterText, FilterRound, FilterFrom, FilterTo })
        {
            edit.Clear();
        }
    }

    public void SetHeader(string name, NetUserId target)
    {
        TargetLabel.Text = name;
        TargetIdLabel.Text = target.UserId.ToString();
    }

    public void SetLoading()
    {
        SetStatus(Loc.GetString("ahelp-history-loading"));
    }

    public void ShowError(string error)
    {
        SetStatus(Loc.GetString(error switch
        {
            "rate-limited" => "ahelp-history-error-rate-limited",
            "bad-filters" => "ahelp-history-error-bad-filters",
            _ => "ahelp-history-error",
        }));
    }

    public void SetEntries(List<AhelpHistoryEntry> entries, bool hasMore, int skip, int? anchorId, bool showMoveTo)
    {
        HistoryContainer.RemoveAllChildren();

        BoxContainer? roundBody = null;

        for (var i = 0; i < entries.Count; i++)
        {
            var entry = entries[i];

            if (i == 0 || entries[i - 1].RoundId != entry.RoundId)
            {
                var panel = new PanelContainer
                {
                    StyleClasses = { StyleNano.StyleClassMaidTexturedBackground },
                    HorizontalExpand = true,
                    Margin = new Thickness(0, 0, 0, 8),
                };
                HistoryContainer.AddChild(panel);

                roundBody = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    HorizontalExpand = true,
                };
                panel.AddChild(roundBody);

                roundBody.AddChild(new AhelpHistoryRoundHeader(entry));
            }

            var card = new AhelpHistoryCard(
                entry,
                isAnchor: entry.Id == anchorId,
                showMoveTo: showMoveTo);
            card.MoveToRequested += MoveToRequested;
            roundBody?.AddChild(card);
        }

        NoEntriesLabel.Visible = entries.Count == 0;

        if (entries.Count == 0)
        {
            ClearStatus();
        }
        else
        {
            var from = skip + 1;
            var to = skip + entries.Count;
            SetStatus(Loc.GetString("ahelp-history-page-info", ("from", from), ("to", to)));
        }

        PrevPageButton.Disabled = skip <= 0;
        NextPageButton.Disabled = !hasMore;
    }

    private void SetStatus(string text)
    {
        StatusLabel.Visible = true;
        StatusLabel.Text = text;
    }

    private void ClearStatus()
    {
        StatusLabel.Visible = false;
        StatusLabel.Text = string.Empty;
    }

    public bool ParseFilters(out int? roundId, out DateTime? from, out DateTime? to, out string text)
    {
        roundId = null;
        from = null;
        to = null;
        text = FilterText.Text.Trim();

        var roundInput = FilterRound.Text.Trim();
        var round = 0;
        var hasRound = roundInput.Length > 0;
        if (hasRound && (!int.TryParse(roundInput, out round) || round < 0))
        {
            ShowError("bad-filters");
            return false;
        }

        roundId = hasRound ? round : null;

        var fromOk = TryParseDate(FilterFrom.Text, isTo: false, out var parsedFrom);
        var toOk = TryParseDate(FilterTo.Text, isTo: true, out var parsedTo);
        if (!fromOk || !toOk)
        {
            ShowError("bad-filters");
            return false;
        }

        from = parsedFrom;
        to = parsedTo;

        return true;
    }

    private static bool TryParseDate(string input, bool isTo, out DateTime? date)
    {
        date = null;
        input = input.Trim();

        if (input.Length == 0)
            return true;

        var hasTime = input.Contains(':');
        if (!DateTime.TryParseExact(
                input,
                hasTime ? "dd.MM.yyyy HH:mm" : "dd.MM.yyyy",
                CultureInfo.InvariantCulture,
                DateTimeStyles.None,
                out var value))
        {
            return false;
        }

        if (isTo)
        {
            if (hasTime)
            {
                value = value >= DateTime.MaxValue.AddMinutes(-1)
                    ? DateTime.MaxValue
                    : value.AddMinutes(1).AddTicks(-1);
            }
            else if (value.Date >= DateTime.MaxValue.Date)
            {
                value = DateTime.MaxValue;
            }
            else
            {
                value = value.Date.AddDays(1).AddTicks(-1);
            }
        }

        date = value.ToUniversalTime();
        return true;
    }
}
