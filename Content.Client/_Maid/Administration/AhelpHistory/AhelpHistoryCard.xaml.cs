using Content.Shared._Maid.Administration.AhelpHistory;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Maid.Administration.AhelpHistory;

[GenerateTypedNameReferences]
public sealed partial class AhelpHistoryCard : BoxContainer
{
    public event Action<AhelpHistoryEntry>? MoveToRequested;

    public AhelpHistoryCard(AhelpHistoryEntry entry, bool isAnchor = false, bool showMoveTo = false)
    {
        RobustXamlLoader.Load(this);

        MoveToButton.OnPressed += _ => MoveToRequested?.Invoke(entry);
        MoveToButton.Visible = showMoveTo;

        TimeLabel.Text = DateTime.SpecifyKind(entry.SentAt, DateTimeKind.Utc).ToLocalTime().ToString("dd.MM.yyyy HH:mm");
        TimeLabel.Visible = true;

        var senderColor = Color.White;
        if (entry.AdminOnly)
        {
            senderColor = Color.HotPink;
            SetTag(Loc.GetString("ahelp-history-tag-adminonly"), Color.HotPink);
        }
        else if (entry.FromWebhook)
        {
            senderColor = Color.Orange;
            SetTag(Loc.GetString("ahelp-history-tag-webhook"), Color.Orange);
        }
        else if (entry.SenderIsAdmin)
        {
            senderColor = Color.Red;
        }

        SenderLabel.Text = entry.SenderName;
        SenderLabel.FontColorOverride = senderColor;

        if (isAnchor)
        {
            DividerPanel.PanelOverride = new StyleBoxFlat
            {
                BorderColor = Color.Red,
                BorderThickness = new Thickness(0, 0, 0, 2),
            };
        }

        var message = new FormattedMessage();
        message.AddMarkupPermissive(entry.Message);
        MessageText.SetMessage(message);
    }

    private void SetTag(string text, Color color)
    {
        TagLabel.Text = text;
        TagLabel.FontColorOverride = color;
        TagLabel.Visible = true;
    }
}
