using Content.Shared._Maid.Administration.AhelpHistory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Maid.Administration.AhelpHistory;

[GenerateTypedNameReferences]
public sealed partial class AhelpHistoryRoundHeader : BoxContainer
{
    public AhelpHistoryRoundHeader(AhelpHistoryEntry first)
    {
        RobustXamlLoader.Load(this);

        RoundLabel.Text = first.RoundId is { } round
            ? first.RoundServerName.Length > 0
                ? Loc.GetString("ahelp-history-round-header", ("round", round), ("server", first.RoundServerName))
                : Loc.GetString("ahelp-history-round-header-plain", ("round", round))
            : Loc.GetString("ahelp-history-no-round-header");
        RoundLabel.FontColorOverride = Color.Aquamarine;

        if (first.RoundId is { } && first.RoundStartedAtKnown)
        {
            DateLabel.Text = DateTime.SpecifyKind(first.RoundStartedAt, DateTimeKind.Utc).ToLocalTime().ToString("dd.MM.yyyy");
            DateLabel.Visible = true;
        }
    }
}
