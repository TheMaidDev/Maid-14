using Content.Shared._Maid.Extraction;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Maid.Extraction;

/// <summary>
/// Code keypad of the extraction drop pod, same layout as the nuke keypad.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class DropPodMenu : DefaultWindow
{
    public event Action<int>? OnKeypadButtonPressed;
    public event Action? OnClearButtonPressed;
    public event Action? OnEnterButtonPressed;

    private readonly List<Button> _buttons = new();

    public DropPodMenu()
    {
        RobustXamlLoader.Load(this);

        for (var i = 1; i <= 9; i++)
        {
            AddKeypadButton(i);
        }

        AddButton("C", () => OnClearButtonPressed?.Invoke());
        AddKeypadButton(0);
        AddButton("E", () => OnEnterButtonPressed?.Invoke());
    }

    private void AddKeypadButton(int i)
    {
        AddButton(i.ToString(), () => OnKeypadButtonPressed?.Invoke(i));
    }

    private void AddButton(string text, Action onPressed)
    {
        var button = new Button { Text = text, MinSize = new(48, 32) };
        button.OnPressed += _ => onPressed();
        KeypadGrid.AddChild(button);
        _buttons.Add(button);
    }

    public void UpdateState(DropPodUiState state)
    {
        StatusLabel.Text = state.Status switch
        {
            DropPodStatus.WrongCode => Loc.GetString("extraction-pod-ui-wrong-code"),
            DropPodStatus.Unlocked => Loc.GetString("extraction-pod-ui-unlocked"),
            DropPodStatus.Launching => Loc.GetString("extraction-pod-ui-launching"),
            _ => Loc.GetString("extraction-pod-ui-locked"),
        };

        CodeLabel.Text = new string('*', state.EnteredLength) + new string('_', Math.Max(0, state.CodeLength - state.EnteredLength));

        var locked = state.Status is DropPodStatus.Locked or DropPodStatus.WrongCode;
        foreach (var button in _buttons)
        {
            button.Disabled = !locked;
        }
    }
}
