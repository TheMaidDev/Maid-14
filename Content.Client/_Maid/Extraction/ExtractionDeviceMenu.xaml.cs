using Content.Shared._Maid.Extraction;
using Robust.Client.AutoGenerated;
using Robust.Shared.Timing;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Maid.Extraction;

/// <summary>
/// Window of the extraction device: objectives, zone, pod status and the extraction controls.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ExtractionDeviceMenu : DefaultWindow
{
    private static readonly Color DoneColor = Color.FromHex("#3bd16f");
    private static readonly Color NotDoneColor = Color.FromHex("#e04545");

    /// <summary>
    /// How long the re-assignment waits for the second click.
    /// </summary>
    private const float ConfirmTime = 3f;

    /// <summary>
    /// Clicks right after the first one are ignored, so a double click does not confirm by accident.
    /// </summary>
    private const float ConfirmCooldown = 0.5f;

    /// <summary>
    /// Raised when a zone request should be sent: right away the first time, after confirmation for a re-assignment.
    /// </summary>
    public event Action? OnZoneRequested;

    private bool _zoneRequested;
    private bool _confirming;
    private float _confirmLeft;

    public ExtractionDeviceMenu()
    {
        RobustXamlLoader.Load(this);
        ZoneButton.OnPressed += _ => OnZonePressed();
    }

    private void OnZonePressed()
    {
        if (!_zoneRequested)
        {
            OnZoneRequested?.Invoke();
            return;
        }

        if (!_confirming)
        {
            _confirming = true;
            _confirmLeft = ConfirmTime;
            UpdateZoneButtonText();
            return;
        }

        if (ConfirmTime - _confirmLeft < ConfirmCooldown)
            return;

        StopConfirming();
        OnZoneRequested?.Invoke();
    }

    private void StopConfirming()
    {
        _confirming = false;
        UpdateZoneButtonText();
    }

    private void UpdateZoneButtonText()
    {
        ZoneButton.Text = Loc.GetString(_confirming ? "extraction-device-ui-zone-confirm"
            : _zoneRequested ? "extraction-device-ui-zone-reroll"
            : "extraction-device-ui-zone");
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_confirming)
            return;

        _confirmLeft -= args.DeltaSeconds;
        if (_confirmLeft <= 0)
            StopConfirming();
    }

    public void UpdateState(ExtractionDeviceUiState state)
    {
        SetColored(StatusLabel,
            Loc.GetString(state.Unlocked ? "extraction-device-ui-done" : "extraction-device-ui-not-done"),
            state.Unlocked ? DoneColor : NotDoneColor);

        SetText(ProgressLabel, state.Progress);

        ObjectivesList.RemoveAllChildren();
        foreach (var objective in state.Objectives)
        {
            var text = Loc.GetString(objective.Required ? "extraction-device-ui-objective-required" : "extraction-device-ui-objective",
                ("mark", objective.Completed ? "✔" : "✘"),
                ("title", objective.Title));

            var label = new RichTextLabel { HorizontalExpand = true };
            SetColored(label, text, objective.Completed ? DoneColor : NotDoneColor);
            ObjectivesList.AddChild(label);
        }

        SetText(ZoneLabel, Loc.GetString("extraction-device-ui-zone-status", ("zone", state.Zone)));
        SetText(PodLabel, Loc.GetString("extraction-device-ui-pod-status", ("pod", state.Pod)));
        SetText(CodeLabel, state.Code is { } code
            ? Loc.GetString("extraction-device-ui-code", ("code", code))
            : Loc.GetString("extraction-device-ui-code-none"));
        SetText(RerollsLabel, Loc.GetString("extraction-device-ui-rerolls", ("count", state.RerollsLeft)));

        ZoneButton.Disabled = !state.CanRequestZone;
        _zoneRequested = state.ZoneRequested;
        if (!state.CanRequestZone)
            _confirming = false;
        UpdateZoneButtonText();
        PodButton.Disabled = !state.CanCallPod;
    }

    /// <summary>
    /// Rich text labels wrap long lines instead of stretching the window.
    /// </summary>
    private static void SetText(RichTextLabel label, string text)
    {
        label.SetMessage(FormattedMessage.FromUnformatted(text));
    }

    private static void SetColored(RichTextLabel label, string text, Color color)
    {
        var message = new FormattedMessage();
        message.PushColor(color);
        message.AddText(text);
        message.Pop();
        label.SetMessage(message);
    }
}
